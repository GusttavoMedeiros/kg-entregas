test('Postgres: entrega parcial recusa dados inválidos e não altera nada', async () => {
  const db = await bancoComRegrasAtuais();
  try {
    await db.exec(lerMigration('20260928170000_partial_delivery.sql'));
    const ids = await novoPedido(db);
    await quem(db, 'entregador');
    const ok = [{ id: ids.milho, qtd_entregue: 5 }, { id: ids.farelo, qtd_entregue: 2 }];
    const casos = [
      [[{ id: ids.milho, qtd_entregue: 11 }, ok[1]], /inválida/],            // mais do que o pedido
      [[{ id: ids.milho, qtd_entregue: -1 }, ok[1]], /inválida/],
      [[{ id: ids.milho, qtd_entregue: 2.5 }, ok[1]], /inteiro/],
      [[{ id: ids.milho, qtd_entregue: 0 }, { id: ids.farelo, qtd_entregue: 0 }], /Nada foi entregue/],
      [[ok[0]], /cada item/],                                                // falta um item
      [[ok[0], ok[0]], /cada item/],                                         // item repetido
      [[ok[0], { id: 999999, qtd_entregue: 1 }], /inteiro|cada item/],       // item de outro pedido
      [[], /cada item/],
      [{ id: 1 }, /cada item/],
    ];
    for (const [itens, erro] of casos) {
      await assert.rejects(parcial(db, 1, itens), erro, JSON.stringify(itens));
    }
    await assert.rejects(parcial(db, 1, ok, { status_pagamento: 'talvez' }), /resultado do recebimento/);
    await assert.rejects(parcial(db, 1, ok, { status_pagamento: 'pago' }), /forma e a data/);
    await assert.rejects(parcial(db, 404, ok), /não encontrado/);
    await db.exec('reset role');
    const p = (await db.query('select status, valor from public.pedidos')).rows[0];
    assert.equal(p.status, 'pendente');
    assert.equal(Number(p.valor), 200);
    assert.deepEqual((await db.query('select qtd, qtd_pedida from public.itens_pedido order by id')).rows, [{ qtd: 10, qtd_pedida: null }, { qtd: 4, qtd_pedida: null }]);
  } finally { await db.close(); }
});

test('Postgres: pedido pago adiantado não aceita entrega parcial, mas aceita completa', async () => {
  const db = await bancoComRegrasAtuais();
  try {
    await db.exec(lerMigration('20260928170000_partial_delivery.sql'));
    const ids = await novoPedido(db, { status_pagamento: 'pago', forma_pagamento_real: 'pix', data_pagamento: '2026-09-01' });
    for (const role of ['entregador', 'admin']) {
      await quem(db, role);
      await assert.rejects(parcial(db, 1, [{ id: ids.milho, qtd_entregue: 8 }, { id: ids.farelo, qtd_entregue: 4 }]), /Pedido já pago/);
      await db.exec('reset role');
    }
    await quem(db, 'entregador');
    const { r } = (await parcial(db, 1, [{ id: ids.milho, qtd_entregue: 10 }, { id: ids.farelo, qtd_entregue: 4 }], { status_pagamento: 'pendente' })).rows[0];
    assert.equal(r.status, 'entregue');
    assert.equal(r.status_pagamento, 'pago', 'pagamento antecipado preservado');
    assert.equal(r.forma_pagamento_real, 'pix');
    assert.equal(r.data_pagamento, '2026-09-01');
  } finally { await db.close(); }
});

