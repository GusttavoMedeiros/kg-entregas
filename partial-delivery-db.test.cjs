test('Postgres: a nova permissão não abre brechas para o entregador', async () => {
  const db = await bancoComRegrasAtuais();
  try {
    await db.exec(lerMigration('20260928170000_partial_delivery.sql'));
    await novoPedido(db);
    await quem(db, 'entregador');
    // Continua sem poder mexer em valor, descrição ou itens direto na tabela.
    await assert.rejects(db.exec("update public.pedidos set valor=1, status='entregue' where id=1"), /entregador só pode concluir/);
    await assert.rejects(db.exec("update public.pedidos set descricao='x', status='entregue' where id=1"), /entregador só pode concluir/);
    await assert.rejects(db.exec("update public.pedidos set vendedor='admin', status='entregue' where id=1"), /entregador só pode concluir/);
    assert.equal((await db.query("update public.itens_pedido set qtd=1 returning id")).rows.length, 0, 'sem permissão de alterar itens');
    assert.equal((await db.query('delete from public.itens_pedido returning id')).rows.length, 0, 'sem permissão de apagar itens');
    // O sinal da entrega parcial só vale dentro da função e para o pedido dela.
    await db.exec('reset role');
    assert.equal((await db.query("select coalesce(current_setting('kg.entrega_parcial', true), '') as v")).rows[0].v, '');
    // A entrega completa antiga continua igual.
    await quem(db, 'entregador');
    const antiga = (await db.query('select public.concluir_entrega(1,$1::jsonb) as r', [dados()])).rows[0].r;
    assert.equal(antiga.status, 'entregue');
    assert.equal(Number(antiga.valor), 200);
  } finally { await db.close(); }
});

test('Migration de entrega parcial: escopo mínimo e sem apagar dados', () => {
  const sql = lerMigration('20260928170000_partial_delivery.sql');
  assert.match(sql, /add column qtd_pedida integer;/);
  assert.match(sql, /security definer set search_path = ''/);
  assert.match(sql, /revoke all on function public\.concluir_entrega_parcial\(bigint,jsonb,jsonb\) from public, anon;/);
  assert.match(sql, /grant execute on function public\.concluir_entrega_parcial\(bigint,jsonb,jsonb\) to authenticated;/);
  assert.doesNotMatch(sql, /drop table|truncate|drop column|delete from public\.(pedidos|clientes|produtos)\b/i);
  assert.doesNotMatch(sql, /create or replace function public\.concluir_entrega\(/, 'concluir_entrega não muda');
});
